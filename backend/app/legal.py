def _fill_legal(text: str, page_path: str) -> str:
    email = _legal_email() or "не указана"
    revised = _legal_date_display()
    base = public_base_url()
    link = f"{base}{page_path}" if base else page_path
    return (
        text.replace("[Дата]", revised)
        .replace("[E-MAIL]", email)
        .replace("[URL]", link.removeprefix("https://").removeprefix("http://"))
    )


